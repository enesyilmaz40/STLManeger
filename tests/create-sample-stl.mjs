import fs from 'fs';
import path from 'path';

/**
 * Creates a valid binary STL file representing a 3D box of width, height, depth.
 */
export function createBoxSTL(filePath, width = 20, height = 20, depth = 20) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  const w = width / 2;
  const h = height / 2;
  const d = depth / 2;

  // 8 vertices of cube
  const v = [
    [-w, -h, -d], [w, -h, -d], [w, h, -d], [-w, h, -d],
    [-w, -h, d],  [w, -h, d],  [w, h, d],  [-w, h, d]
  ];

  // 12 triangles (2 per face, 6 faces)
  const faces = [
    // Front face (Z = +d)
    [4, 5, 6], [4, 6, 7],
    // Back face (Z = -d)
    [1, 0, 3], [1, 3, 2],
    // Top face (Y = +h)
    [3, 2, 6], [3, 6, 7],
    // Bottom face (Y = -h)
    [4, 5, 1], [4, 1, 0],
    // Right face (X = +w)
    [5, 1, 2], [5, 2, 6],
    // Left face (X = -w)
    [0, 4, 7], [0, 7, 3]
  ];

  const buffer = Buffer.alloc(80 + 4 + faces.length * 50);

  // 80 bytes header
  buffer.write('Binary STL generated by STL Manager Test Suite', 0, 'utf8');

  // Triangle count (UINT32 LE)
  buffer.writeUInt32LE(faces.length, 80);

  let offset = 84;
  for (const f of faces) {
    const v1 = v[f[0]];
    const v2 = v[f[1]];
    const v3 = v[f[2]];

    // Normal (0, 0, 0)
    buffer.writeFloatLE(0, offset);
    buffer.writeFloatLE(0, offset + 4);
    buffer.writeFloatLE(0, offset + 8);

    // Vertex 1
    buffer.writeFloatLE(v1[0], offset + 12);
    buffer.writeFloatLE(v1[1], offset + 16);
    buffer.writeFloatLE(v1[2], offset + 20);

    // Vertex 2
    buffer.writeFloatLE(v2[0], offset + 24);
    buffer.writeFloatLE(v2[1], offset + 28);
    buffer.writeFloatLE(v2[2], offset + 32);

    // Vertex 3
    buffer.writeFloatLE(v3[0], offset + 36);
    buffer.writeFloatLE(v3[1], offset + 40);
    buffer.writeFloatLE(v3[2], offset + 44);

    // Attribute byte count (UINT16)
    buffer.writeUInt16LE(0, offset + 48);

    offset += 50;
  }

  fs.writeFileSync(filePath, buffer);
  return filePath;
}
